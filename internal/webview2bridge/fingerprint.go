func randomFingerprint() browserFingerprint {
	if !FakeFingerprintEnabled {
		return staticFingerprint
	}
	size := windowSizes[rand.Intn(len(windowSizes))]
	return browserFingerprint{
		width:     size[0],
		height:    size[1],
		userAgent: userAgents[rand.Intn(len(userAgents))],
		lang:      langs[rand.Intn(len(langs))],
	}
}
